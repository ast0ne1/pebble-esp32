#!/usr/bin/env python3
"""Bake face art from tools/art into LVGL 9 image C arrays.

Follows the Muse gadget approach for sharp round panels:
  - compose / crop at native 466×466 (no runtime scale)
  - LANCZOS when resizing
  - 4×4 Bayer ordered dither into RGB565 (soft gradients without banding)
"""
from __future__ import annotations

from pathlib import Path

from PIL import Image, ImageDraw

FW = Path(__file__).resolve().parents[1]
SRC = FW / "tools" / "art"
OUT = FW / "main" / "assets"

PANEL = 466
# Muse-like buddy: smaller than full-bleed, but clear enough to read feet/face.
FACE = 280

# 4×4 Bayer matrix — same idea as muse-gadget-sdk avatar shading
_BAYER4 = (
    (0, 8, 2, 10),
    (12, 4, 14, 6),
    (3, 11, 1, 9),
    (15, 7, 13, 5),
)


def bayer(x: int, y: int) -> float:
    """Threshold in [-0.5, 0.5) for ordered dither."""
    return _BAYER4[y & 3][x & 3] / 16.0 - 0.5


def rgb565_dither(r: int, g: int, b: int, x: int, y: int) -> int:
    """Quantize 8-bit RGB → RGB565 with Bayer dither (Muse-style soft edges)."""
    t = bayer(x, y)
    r = max(0, min(255, int(r + t * 8)))
    g = max(0, min(255, int(g + t * 4)))
    b = max(0, min(255, int(b + t * 8)))
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def _write_c(name: str, body: bytes, w: int, h: int, cf: str, stride: int) -> None:
    lines = [
        "/* Generated by tools/mkassets.py — do not edit. */",
        '#include "lvgl.h"',
        "",
        f"static const uint8_t {name}_map[] = {{",
    ]
    for i in range(0, len(body), 16):
        chunk = "".join(f"0x{b:02X}," for b in body[i : i + 16])
        lines.append("    " + chunk)
    lines.append("};")
    lines.append(
        f"""
const lv_image_dsc_t {name} = {{
    .header = {{
        .magic  = LV_IMAGE_HEADER_MAGIC,
        .cf     = {cf},
        .flags  = 0,
        .w      = {w},
        .h      = {h},
        .stride = {stride},
        .reserved_2 = 0,
    }},
    .data_size = {len(body)},
    .data = {name}_map,
}};
"""
    )
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"{name}.c").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"  {name} {w}x{h} {cf} ({len(body) // 1024} KB)")


def emit_rgb565(name: str, img: Image.Image) -> None:
    img = img.convert("RGB")
    w, h = img.size
    px = img.load()
    body = bytearray()
    for y in range(h):
        for x in range(w):
            r, g, b = px[x, y]
            v = rgb565_dither(r, g, b, x, y)
            body += bytes((v & 0xFF, v >> 8))
    _write_c(name, bytes(body), w, h, "LV_COLOR_FORMAT_RGB565", w * 2)


def cover_square(
    path: Path, size: int, focus_y: float = 0.5, zoom: float = 1.0
) -> Image.Image:
    im = Image.open(path).convert("RGB")
    w, h = im.size
    scale = max(size / w, size / h) * max(zoom, 1.0)
    nw, nh = int(w * scale + 0.5), int(h * scale + 0.5)
    im = im.resize((nw, nh), Image.Resampling.LANCZOS)
    left = (nw - size) // 2
    top = int((nh - size) * focus_y)
    top = max(0, min(nh - size, top))
    return im.crop((left, top, left + size, top + size))


def soft_circle_rgba(im: Image.Image, solid: float = 0.52, fade: float = 0.78) -> Image.Image:
    """HTML-like radial mask into true alpha (then precomposited onto splash)."""
    im = im.convert("RGBA")
    w, h = im.size
    cx, cy = (w - 1) / 2.0, (h - 1) / 2.0
    r = min(cx, cy)
    r_solid, r_fade = r * solid, r * fade
    out = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    src, dst = im.load(), out.load()
    for y in range(h):
        for x in range(w):
            d = ((x - cx) ** 2 + (y - cy) ** 2) ** 0.5
            if d <= r_solid:
                a = 1.0
            elif d >= r_fade:
                a = 0.0
            else:
                t = (d - r_solid) / (r_fade - r_solid)
                a = (1.0 - t) * (1.0 - t)
            if a <= 0.0:
                continue
            s = src[x, y]
            dst[x, y] = (s[0], s[1], s[2], int(a * 255 + 0.5))
    return out


UI_BG = (21, 24, 26)  # shell COL_UI #15181A — round bezel corners


def round_panel(im: Image.Image, bg=UI_BG, solid: float = 0.96, fade: float = 1.0) -> Image.Image:
    """Feather square art into the round panel so corners aren't a hard box."""
    rgba = soft_circle_rgba(im, solid=solid, fade=fade)
    base = Image.new("RGBA", rgba.size, (*bg, 255))
    return Image.alpha_composite(base, rgba).convert("RGB")


def make_mark_rgba(size: int = 84) -> Image.Image:
    """Cairn mark supersampled 4× then LANCZOS-down — kills the jaggy polygon edges."""
    ss = 4
    big = size * ss
    mark = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    draw = ImageDraw.Draw(mark)

    def pt(x, y):
        return (8 * ss + (x - 8) * (big - 16 * ss) / 84, 8 * ss + (y - 8) * (big - 16 * ss) / 84)

    def poly(points, fill):
        draw.polygon([pt(x, y) for x, y in points], fill=fill)

    poly([(20, 32), (80, 8), (80, 20), (32, 39.2), (32, 46.2), (20, 51)], (168, 152, 124, 255))
    poly([(20, 56), (80, 32), (80, 44), (20, 68)], (110, 116, 122, 255))
    poly([(80, 68), (20, 92), (20, 80), (68, 60.8), (68, 53.8), (80, 49)], (63, 68, 72, 255))
    return mark.resize((size, size), Image.Resampling.LANCZOS)


def radial_splash_bg(size: int = PANEL) -> Image.Image:
    """HTML boot wash: radial at 50% 42% — #2a2620 → #15181a → #0b0d0e."""
    img = Image.new("RGB", (size, size), (11, 13, 14))
    px = img.load()
    cx, cy = (size - 1) / 2.0, size * 0.42
    r_max = size * 0.72
    c0, c1, c2 = (42, 38, 32), (21, 24, 26), (11, 13, 14)
    for y in range(size):
        for x in range(size):
            d = ((x - cx) ** 2 + (y - cy) ** 2) ** 0.5 / r_max
            if d < 0.55:
                t = d / 0.55
                # ease to mid
                t = t * t
                r = int(c0[0] + (c1[0] - c0[0]) * t)
                g = int(c0[1] + (c1[1] - c0[1]) * t)
                b = int(c0[2] + (c1[2] - c0[2]) * t)
            elif d < 1.0:
                t = (d - 0.55) / 0.45
                r = int(c1[0] + (c2[0] - c1[0]) * t)
                g = int(c1[1] + (c2[1] - c1[1]) * t)
                b = int(c1[2] + (c2[2] - c1[2]) * t)
            else:
                r, g, b = c2
            px[x, y] = (r, g, b)
    return img


def compose_splash_plate() -> Image.Image:
    """Full native-res splash graphics (text stays LVGL). Muse-style: one plate, no runtime scale."""
    plate = radial_splash_bg(PANEL).convert("RGBA")

    mark = make_mark_rgba(84)
    # Splash buddy: wider solid disc so the vignette eats less of the face.
    splash_face = 184
    buddy = soft_circle_rgba(
        cover_square(SRC / "pebble-face-wave.jpg", splash_face, focus_y=0.38, zoom=1.02),
        solid=0.94,
        fade=1.0,
    )

    # Flex-like stack (mark → LVGL text band → buddy). Extra gap drops buddy
    # below the subtitle so type and face don't crowd.
    text_to_buddy = 28
    content_h = 84 + 12 + 28 + 8 + 18 + text_to_buddy + splash_face
    y0 = (PANEL - content_h) // 2
    mx = (PANEL - 84) // 2
    plate.alpha_composite(mark, (mx, y0))
    by = y0 + 84 + 12 + 28 + 8 + 18 + text_to_buddy
    bx = (PANEL - splash_face) // 2
    plate.alpha_composite(buddy, (bx, by))
    return plate.convert("RGB")


def radial_home_bg(size: int = PANEL) -> Image.Image:
    """Quiet field — slight lift under the buddy so he isn't swallowed by black."""
    img = Image.new("RGB", (size, size), UI_BG)
    px = img.load()
    cx, cy = (size - 1) / 2.0, (size - 1) / 2.0 + size * 0.06
    r_max = size * 0.48
    c0, c1 = (48, 44, 38), UI_BG
    for y in range(size):
        for x in range(size):
            d = ((x - cx) ** 2 + (y - cy) ** 2) ** 0.5 / r_max
            if d >= 1.0:
                px[x, y] = c1
                continue
            t = d * d
            r = int(c0[0] + (c1[0] - c0[0]) * t)
            g = int(c0[1] + (c1[1] - c0[1]) * t)
            b = int(c0[2] + (c1[2] - c0[2]) * t)
            px[x, y] = (r, g, b)
    return img


def compose_face_plate(src_name: str) -> Image.Image:
    """Buddy ~60% disc, soft edge kept tight so feet/face stay readable."""
    plate = radial_home_bg(PANEL).convert("RGBA")
    buddy = soft_circle_rgba(
        cover_square(SRC / src_name, FACE, focus_y=0.44, zoom=1.04),
        solid=0.90,
        fade=0.99,
    )
    bx = (PANEL - FACE) // 2
    # Mild nudge down for clock band — not so far that feet clip the bezel.
    by = (PANEL - FACE) // 2 + 22
    plate.alpha_composite(buddy, (bx, by))
    return round_panel(plate.convert("RGB"), bg=UI_BG, solid=0.97, fade=1.0)


def main():
    print(f"src: {SRC}")
    print(f"out: {OUT}")

    # Home faces — 466 plate, buddy ~FACE px (not full-bleed)
    for name, src in (
        ("img_pebble_idle", "pebble-idle.jpg"),
        ("img_pebble_listening", "pebble-listening.jpg"),
        ("img_pebble_thinking", "pebble-thinking.jpg"),
        ("img_pebble_worried", "pebble-worried.jpg"),
    ):
        emit_rgb565(name, compose_face_plate(src))

    # Full-bleed splash plate (AA mark + soft buddy + radial) — sharp like Muse plates
    emit_rgb565("img_pebble_splash", compose_splash_plate())

    # Keep small soft assets for any other use (supersampled mark)
    emit_rgb565(
        "img_pebble_wave",
        Image.alpha_composite(
            Image.new("RGBA", (178, 178), (11, 13, 14, 255)),
            soft_circle_rgba(
                cover_square(SRC / "pebble-face-wave.jpg", 178, focus_y=0.40, zoom=1.05)
            ),
        ).convert("RGB"),
    )
    # Mark on dark for standalone; splash plate already has the AA version
    mark_rgb = Image.new("RGB", (84, 84), (11, 13, 14))
    mark_rgb.paste(make_mark_rgba(84), (0, 0), make_mark_rgba(84))
    emit_rgb565("img_stonepi_mark", mark_rgb)

    names = [
        "img_pebble_idle",
        "img_pebble_listening",
        "img_pebble_thinking",
        "img_pebble_worried",
        "img_pebble_splash",
        "img_pebble_wave",
        "img_stonepi_mark",
    ]
    (OUT / "assets.h").write_text(
        "/* Generated by tools/mkassets.py (+ nudge PCM) */\n"
        "#pragma once\n"
        "#include \"lvgl.h\"\n"
        "#include <stddef.h>\n"
        "#include <stdint.h>\n\n"
        + "\n".join(f"extern const lv_image_dsc_t {n};" for n in names)
        + "\n\n"
        "/* Short character chirps @ 22050 Hz mono int16 (nudge / tap). */\n"
        "extern const int16_t pcm_nudge0[];\n"
        "extern const size_t  pcm_nudge0_len;\n"
        "extern const int16_t pcm_nudge1[];\n"
        "extern const size_t  pcm_nudge1_len;\n"
        "extern const int16_t pcm_nudge2[];\n"
        "extern const size_t  pcm_nudge2_len;\n",
        encoding="utf-8",
    )
    print("wrote assets.h")


if __name__ == "__main__":
    main()
